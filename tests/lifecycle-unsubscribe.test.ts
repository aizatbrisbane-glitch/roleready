// ─────────────────────────────────────────────────────────────────────────────
// Token security: cross-user protection
// ─────────────────────────────────────────────────────────────────────────────

describe("Cross-user token security", () => {

  it("token for user A cannot be used to unsubscribe user B", async () => {
    // With DB-backed tokens, user A's token only matches their email_preferences
    // row. Even if user B's token happens to be guessed (it can't — 256 bits),
    // the DB update filters by unsubscribe_token AND preference_type together.
    // We verify the contract: if the mock returns 0 rows (token not for this
    // user), the route redirects to an error page, not /confirmed.
    state.updateResult = { data: [], error: null };
    const someToken = createUnsubscribeToken(); // valid format, not in DB
    const res = await formPost(makeFormPost(someToken));
    expect(res.headers.get("location")).not.toContain("/confirmed");
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// Secret-free design verification
// ─────────────────────────────────────────────────────────────────────────────

describe("Secret-free design", () => {

  it("LIFECYCLE_UNSUBSCRIBE_SECRET is not required for any operation", async () => {
    const saved = process.env.LIFECYCLE_UNSUBSCRIBE_SECRET;
    delete process.env.LIFECYCLE_UNSUBSCRIBE_SECRET;

    // Token creation still works
    const token = createUnsubscribeToken();
    expect(isPlausibleToken(token)).toBe(true);

    // Route still works (DB is the auth, not a secret)
    const res = await formPost(makeFormPost(token));
    expect(res.status).toBe(303);

    if (saved !== undefined) process.env.LIFECYCLE_UNSUBSCRIBE_SECRET = saved;
  });

  it("there is no secret fallback to RESEND_API_KEY", () => {
    // The lib must not import or read RESEND_API_KEY for token operations.
    // We verify by checking the module source doesn't reference it.
    // (Behavioural: if it did, this test would catch accidental regressions.)
    const moduleSource = require("fs")
      .readFileSync(require("path").resolve(__dirname, "../lib/lifecycle-unsubscribe.ts"), "utf8");
    expect(moduleSource).not.toContain("RESEND_API_KEY");
  });
});
