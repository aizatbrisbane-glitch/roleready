import { createHash, randomBytes } from "crypto";

// ─── Design rationale ─────────────────────────────────────────────────────────
//
// Tokens are 32 cryptographically random bytes (256 bits), base64url-encoded.
// The EMAIL contains the plaintext token; the DATABASE stores only SHA-256(token).
//
// Why store a hash?
//   • Defense-in-depth: even a full DB read (compromised service_role key,
//     Supabase data breach) cannot extract tokens to silently mass-unsubscribe
//     users. 256-bit preimages are computationally infeasible to reverse.
//   • email_preferences is service_role-only, but defence against DB-level
//     breaches is cheap and worthwhile.
//
// Key properties:
//   • Never expire — an email sent months ago still has a working unsub link.
//   • Independently revocable — rotate one user's token without affecting others.
//   • No shared secret — security comes from randomness, not a key to rotate.
//   • One token per (user_id, reminder_type) row. If the row is updated for a
//     retry, a new token is generated; the prior email's link is invalidated.
//     For a two-email sequence (reminder_1, reminder_2) with separate rows,
//     each row has its own independent token and hash.

export function createUnsubscribeToken(): string {
  return randomBytes(32).toString("base64url");
}

export function hashUnsubscribeToken(token: string): string {
  return createHash("sha256").update(token).digest("hex");
}

// Light format check used before hitting the database — not a security gate.
// A valid token is a base64url string. Tokens generated by createUnsubscribeToken
// are exactly 43 characters; allow up to 256 for future flexibility.
export function isPlausibleToken(token: unknown): token is string {
  return (
    typeof token === "string" &&
    token.length >= 32 &&
    token.length <= 256 &&
    /^[A-Za-z0-9_-]+$/.test(token)
  );
}
